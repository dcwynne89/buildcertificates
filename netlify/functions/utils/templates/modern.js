/* ============================================================
   modern.js — "Executive" template
   Pure white, full-width indigo→purple gradient header,
   white title inside header, 85px Inter 900 name below,
   large gray course text, minimal bottom row.
   ============================================================ */

module.exports = function modernTemplate(data, options = {}) {
  const accentA = "#3730A3"; // Indigo
  const accentB = "#7C3AED"; // Purple
  const color   = options.color || accentA;

  const { recipient = {}, certificate = {}, verifyId, qrDataUrl } = data;
  const recipientName = recipient.name            || "Recipient Name";
  const certTitle     = certificate.title         || "Certificate of Completion";
  const courseName    = certificate.course        || "";
  const rawDate       = certificate.date
    ? new Date(certificate.date + "T12:00:00").toLocaleDateString("en-US", { year:"numeric", month:"long", day:"numeric" })
    : new Date().toLocaleDateString("en-US", { year:"numeric", month:"long", day:"numeric" });
  const issuerName    = certificate.issuer        || "";
  const issuerTitle   = certificate.issuer_title  || "";
  const watermark     = options.watermark || false;

  const qrHtml = qrDataUrl
    ? `<img src="${qrDataUrl}" class="qr-img" alt="Verify"/>`
    : "";

  const watermarkHtml = watermark
    ? `<div class="watermark">Generated by BuildCertificates.com</div>`
    : "";

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<style>
  @import url('https://fonts.googleapis.com/css2?family=Inter:wght@300;400;500;600;700;800;900&family=Dancing+Script:wght@600;700&display=swap');

  * { margin:0; padding:0; box-sizing:border-box; }
  html, body { width:11in; height:8.5in; overflow:hidden; background:#fff; }
  .page { width:11in; height:8.5in; position:relative; background:#fff; display:flex; flex-direction:column; overflow:hidden; }

  /* ── Gradient header ── */
  .header {
    flex-shrink: 0;
    height: 2.0in;
    background: linear-gradient(135deg, ${color} 0%, ${accentB} 100%);
    position: relative;
    display: flex;
    flex-direction: column;
    align-items: center;
    justify-content: center;
    padding: 0 0.7in;
  }
  .header::after {
    content: '';
    position: absolute;
    bottom: 0; left: 0; right: 0;
    height: 4px;
    background: rgba(255,255,255,0.15);
  }

  .header-eyebrow {
    font-family: 'Inter', sans-serif;
    font-size: 10px;
    font-weight: 500;
    color: rgba(255,255,255,0.65);
    letter-spacing: 6px;
    text-transform: uppercase;
    margin-bottom: 8px;
  }

  .header-title {
    font-family: 'Inter', sans-serif;
    font-size: 32px;
    font-weight: 800;
    color: #fff;
    letter-spacing: 5px;
    text-transform: uppercase;
    text-align: center;
    line-height: 1;
    margin-bottom: 12px;
  }

  .header-rule {
    width: 260px;
    height: 1px;
    background: rgba(255,255,255,0.35);
  }

  /* ── Body ── */
  .body {
    flex: 1;
    display: flex;
    flex-direction: column;
    padding: 0.42in 0.7in 0.28in;
  }

  .presented {
    font-family: 'Inter', sans-serif;
    font-size: 12px;
    font-weight: 400;
    color: #aaa;
    letter-spacing: 3px;
    text-transform: uppercase;
    margin-bottom: 0.06in;
  }

  .recipient-name {
    font-family: 'Inter', sans-serif;
    font-size: 85px;
    font-weight: 900;
    color: #0f0f0f;
    line-height: 0.95;
    letter-spacing: -3px;
    margin-bottom: 0.18in;
  }

  .divider {
    width: 60px;
    height: 4px;
    background: ${color};
    border-radius: 2px;
    margin-bottom: 0.14in;
  }

  .course-block { margin-bottom: auto; }
  .course-intro { font-family:'Inter',sans-serif; font-size:18px; font-weight:400; color:#888; line-height:1.4; }
  .course-name  { font-family:'Inter',sans-serif; font-size:18px; font-weight:700; color:#555; line-height:1.4; }

  /* ── Bottom bar ── */
  .bottom {
    display: flex;
    align-items: flex-end;
    justify-content: space-between;
    padding-top: 0.18in;
    border-top: 1px solid #f0f0f0;
  }

  .meta-block { display:flex; flex-direction:column; gap:3px; }
  .meta-date   { font-family:'Inter',sans-serif; font-size:14px; color:#999; }
  .meta-issuer { font-family:'Inter',sans-serif; font-size:15px; font-weight:700; color:#222; }

  .sig-block { display:flex; flex-direction:column; align-items:center; }
  .sig-script { font-family:'Dancing Script',cursive; font-size:28px; color:#333; line-height:1; margin-bottom:4px; }
  .sig-line   { width:180px; height:1px; background:#ddd; margin-bottom:5px; }
  .sig-label  { font-family:'Inter',sans-serif; font-size:10px; color:#bbb; letter-spacing:2px; }

  .qr-wrap { display:flex; flex-direction:column; align-items:flex-end; }
  .qr-img  { width:62px; height:62px; }

  .watermark { text-align:center; font-size:8px; color:#ddd; padding:3px 0; font-family:'Inter',sans-serif; }
</style>
</head>
<body>
<div class="page">

  <!-- Gradient header -->
  <div class="header">
    <div class="header-eyebrow">Official Document</div>
    <div class="header-title">${certTitle}</div>
    <div class="header-rule"></div>
  </div>

  <!-- Body -->
  <div class="body">
    <div class="presented">Presented to</div>
    <div class="recipient-name">${recipientName}</div>
    <div class="divider"></div>

    ${courseName ? `
    <div class="course-block">
      <div class="course-intro">For successfully completing</div>
      <div class="course-name">${courseName}</div>
    </div>
    ` : `<div style="flex:1;"></div>`}

    <div class="bottom">
      <div class="meta-block">
        <div class="meta-date">${rawDate}</div>
        ${issuerName ? `<div class="meta-issuer">${issuerName}</div>` : ""}
      </div>
      <div class="sig-block">
        <div class="sig-script">${issuerTitle || issuerName || "Signature"}</div>
        <div class="sig-line"></div>
        <div class="sig-label">Authorized Signature</div>
      </div>
      <div class="qr-wrap">${qrHtml}</div>
    </div>
  </div>

  ${watermarkHtml}
</div>
</body>
</html>`;
};
